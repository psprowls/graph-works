"""Strip the retired machine-ownership comment from live proposal bodies.

Both renderers once opened a proposal body with an HTML comment announcing that
the body is machine-owned. They no longer emit it, and `plan_propose` refuses
`unrenderable-body` on any body that still carries it, so the live proposals
have to lose it in the same change (epic decisions D-002 and D-008).

**Scope.** A candidate is a `type: Proposal` document under `proposals/` but not
`proposals/_archive/`, with `page_status: proposed`. A decided body is
human-owned and frozen (`okf_ext.proposals.plan`), and the old-dialect migrator
refuses to re-render archived bodies for the same reason (`migrate.py`). Scope
comes from the path prefix as well as the type, so a clone's fixture under
`repositories/` is never a candidate.

**Shape-gated, not render-gated.** A body is stripped when its first line is one
of two exact shapes -- the one-line current header, or the legacy two-line
header -- followed by exactly one blank line. Whether the rest of the body can
be reproduced by a renderer is deliberately not asked (D-008). Every other byte,
terminators included, is carried through verbatim.

Refusals are data, all-or-nothing per document; the other documents proceed. A
body that does not start with `<!--` is skipped silently, which is what makes a
re-run an empty plan.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from okf_ext.proposals import PROPOSAL_TYPE, list_proposals
from okf_ext.writing import ApplyResult, PendingWrite, WriteFailure, body_digest, write_all
from okf_io import Bundle
from okf_io.document import rendered_with_body

_CURRENT_HEADER = (
    "<!-- Generated by `okf_ext.proposals` while `page_status: proposed`. "
    "Every byte below is machine-owned and is regenerated on each merge; "
    "it is never touched once this proposal is decided. -->"
)
_LEGACY_LINE_1 = "<!-- Body regenerated from origins[] while status: proposed. Do not edit here;"
_LEGACY_LINE_2 = re.compile(r"^     approve via `gw wiki proposal approve [^`]+`\. -->$")

_LIVE_PREFIX = "proposals/"
_ARCHIVE_PREFIX = "proposals/_archive/"

RefusalKind = Literal["unrecognised-header", "missing-separator", "unreadable"]


@dataclass(frozen=True, slots=True)
class Refusal:
    member: str
    kind: RefusalKind
    detail: str


@dataclass(frozen=True, slots=True)
class StripWrite:
    member: str
    text: str  # the whole file as it will land
    digest: str  # body_digest of the body planned against


@dataclass(frozen=True, slots=True)
class StripPlan:
    root: Path
    writes: tuple[StripWrite, ...]
    refusals: tuple[Refusal, ...]

    @property
    def ok(self) -> bool:
        return not self.refusals

    @property
    def is_empty(self) -> bool:
        return not self.writes


def _bare(line: str) -> str:
    return line.rstrip("\r\n")


def strip_header_body(body: str) -> str | RefusalKind | None:
    """The stripped body, a refusal kind, or `None` when there is no leading comment."""
    lines = body.splitlines(keepends=True)
    if not lines or not lines[0].startswith("<!--"):
        return None
    if _bare(lines[0]) == _CURRENT_HEADER:
        count = 1
    elif _bare(lines[0]) == _LEGACY_LINE_1 and len(lines) > 1 and _LEGACY_LINE_2.fullmatch(_bare(lines[1])):
        count = 2
    else:
        return "unrecognised-header"
    if count >= len(lines) or _bare(lines[count]) != "":
        return "missing-separator"
    if count + 1 < len(lines) and _bare(lines[count + 1]) == "":
        return "missing-separator"
    return "".join(lines[count + 1 :])


def _in_scope(member: str) -> bool:
    return member.startswith(_LIVE_PREFIX) and not member.startswith(_ARCHIVE_PREFIX)


def plan_strip_header(bundle: Bundle) -> StripPlan:
    """Plan the strip against *bundle*. Writes nothing."""
    writes: list[StripWrite] = []
    refusals: list[Refusal] = []
    for proposal in list_proposals(bundle, page_status="proposed"):
        if not _in_scope(proposal.member):
            continue
        document = bundle.concepts[proposal.concept_id]
        outcome = strip_header_body(document.body)
        if outcome is None:
            continue
        if outcome in ("unrecognised-header", "missing-separator"):
            detail = (
                "the body starts with an HTML comment that is not a known proposal header"
                if outcome == "unrecognised-header"
                else "the header is not followed by exactly one blank line"
            )
            refusals.append(Refusal(proposal.member, outcome, detail))  # type: ignore[arg-type]
            continue
        writes.append(StripWrite(proposal.member, rendered_with_body(document, outcome), body_digest(document.body)))
    for concept_id, document in sorted(bundle.concepts.items()):
        member = f"{concept_id}.md"
        if document.parse_error is None or not _in_scope(member):
            continue
        raw = document.raw_text
        if f"type: {PROPOSAL_TYPE}" in raw and "page_status: proposed" in raw:
            refusals.append(
                Refusal(
                    member,
                    "unreadable",
                    f"failed to parse ({document.parse_error.kind}): {document.parse_error.message}",
                )
            )
    return StripPlan(
        root=Path(bundle.root),
        writes=tuple(sorted(writes, key=lambda w: w.member)),
        refusals=tuple(sorted(refusals, key=lambda r: r.member)),
    )


def apply(bundle: Bundle, plan: StripPlan) -> ApplyResult:
    """Write *plan* against *bundle*; a drifted or unparseable document is refused.

    Does not gate on `plan.ok`: nothing is computed across documents. Raises
    `ValueError` for a plan built against a different bundle.
    """
    if Path(plan.root).resolve() != Path(bundle.root).resolve():
        raise ValueError(
            f"Plan was built against a different bundle ({plan.root}), not {bundle.root}. "
            f"A plan's digests mean nothing outside the bundle it was planned against."
        )
    failed: list[WriteFailure] = []
    pending: list[PendingWrite] = []
    for write in plan.writes:
        concept_id = write.member[: -len(".md")] if write.member.endswith(".md") else write.member
        document = bundle.concepts.get(concept_id)
        if document is None or document.path is None:
            failed.append(WriteFailure(path=write.member, kind="not-a-member", error="not a member of this bundle"))
            continue
        if document.parse_error is not None:
            failed.append(
                WriteFailure(
                    path=write.member,
                    kind="parse-error",
                    error=(
                        f"cannot rewrite a document that failed to parse "
                        f"({document.parse_error.kind}): {document.parse_error.message}"
                    ),
                )
            )
            continue
        if body_digest(document.body) != write.digest:
            failed.append(
                WriteFailure(
                    path=write.member,
                    kind="stale",
                    error="stale plan: the body changed since it was planned; re-plan against the current bundle",
                )
            )
            continue
        pending.append(
            PendingWrite(member=write.member, path=document.path, rendered=write.text, on_written=lambda: None)
        )
    return write_all(pending, failed=failed)
